/**
 * Generates lib/types.ts from the Python pydantic models (never hand-written).
 *
 * 1. Runs `python -m bowlsense.schemas --with-api` (ml/.venv) to export the JSON Schema of
 *    every data contract and API body into lib/bowlsense.api.schema.json.
 * 2. Compiles that schema to TypeScript with json-schema-to-typescript.
 *
 * Usage: npm run gen-types   (pass --no-export to reuse the existing schema file)
 */
import { execFileSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { compile, type JSONSchema } from "json-schema-to-typescript";

const web = path.resolve(import.meta.dirname, "..");
const ml = path.resolve(web, "..", "ml");
const schemaFile = path.join(web, "lib", "bowlsense.api.schema.json");
const outFile = path.join(web, "lib", "types.ts");

function python(): string {
  const candidates = [
    path.join(ml, ".venv", "Scripts", "python.exe"),
    path.join(ml, ".venv", "bin", "python"),
  ];
  const found = candidates.find((p) => existsSync(p));
  if (!found) throw new Error(`No Python venv in ${ml}/.venv; run scripts/setup.py first.`);
  return found;
}

type Json = null | boolean | number | string | Json[] | { [key: string]: Json };

/**
 * Make pydantic's draft-2020 schema friendly to json-schema-to-typescript:
 * - drop property-level titles (they would become one alias type per field);
 * - turn tuple `prefixItems` into draft-07 tuple `items` arrays.
 */
function normalise(node: Json, isProperty = false): Json {
  if (Array.isArray(node)) return node.map((n) => normalise(n));
  if (node === null || typeof node !== "object") return node;
  const out: { [key: string]: Json } = {};
  for (const [key, value] of Object.entries(node)) {
    if (key === "title" && isProperty) continue;
    if (key === "properties" && value && typeof value === "object" && !Array.isArray(value)) {
      out[key] = Object.fromEntries(Object.entries(value).map(([k, v]) => [k, normalise(v, true)]));
    } else if (key === "prefixItems" && Array.isArray(value)) {
      out.items = value.map((v) => normalise(v));
      out.minItems = value.length;
      out.maxItems = value.length;
    } else {
      out[key] = normalise(value, isProperty && (key === "anyOf" || key === "items"));
    }
  }
  return out;
}

async function main(): Promise<void> {
  if (!process.argv.includes("--no-export")) {
    execFileSync(python(), ["-m", "bowlsense.schemas", "--with-api", "--out", schemaFile], {
      cwd: ml,
      stdio: "inherit",
    });
  }
  const schema = normalise(JSON.parse(readFileSync(schemaFile, "utf-8"))) as JSONSchema;
  const ts = await compile(schema, "BowlSense", {
    bannerComment:
      "/** Generated by scripts/gen-types.ts from ml/bowlsense (pydantic). Do not edit. */",
    additionalProperties: false,
    unreachableDefinitions: true,
    declareExternallyReferenced: true,
    style: { singleQuote: false, semi: true, printWidth: 100 },
  });
  writeFileSync(outFile, ts, "utf-8");
  console.log(`wrote ${path.relative(web, outFile)}`);
}

main().catch((err: unknown) => {
  console.error(err);
  process.exit(1);
});
